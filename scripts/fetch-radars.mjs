// Downloads official CS2 radar overviews + Valve radar_info metadata
// from github.com/MurkyYT/cs2-map-icons, then generates shared map metadata.
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const BASE = "https://raw.githubusercontent.com/MurkyYT/cs2-map-icons/main";
// Active CS2 competitive / Active Duty pool (+ recent returns).
const MAPS = [
  "de_ancient",
  "de_anubis",
  "de_cache",
  "de_dust2",
  "de_inferno",
  "de_mirage",
  "de_nuke",
  "de_overpass",
  "de_train",
  "de_vertigo",
];
const OUT_IMG = path.join(ROOT, "apps/web/public/maps");
const OUT_META = path.join(ROOT, "packages/shared/src/maps.generated.ts");

function num(txt, key) {
  const m = txt.match(new RegExp(`"${key}"\\s+"([-\\d.]+)"`));
  return m ? Number(m[1]) : null;
}

function point(txt, prefix) {
  const x = num(txt, `${prefix}_x`);
  const y = num(txt, `${prefix}_y`);
  return x == null || y == null ? null : [x, y];
}

function lowerSplit(txt) {
  const lower = txt.match(/"lower"[^{]*\{[^}]*"AltitudeMax"\s+"([-\d.]+)"/);
  return lower ? Number(lower[1]) : null;
}

async function download(url, dest) {
  const res = await fetch(url);
  if (!res.ok) return false;
  await fs.writeFile(dest, Buffer.from(await res.arrayBuffer()));
  return true;
}

await fs.mkdir(OUT_IMG, { recursive: true });
const meta = {};

for (const map of MAPS) {
  const info = await (await fetch(`${BASE}/data/radar_info/${map}.txt`)).text();
  const hasLower = await download(
    `${BASE}/images/radars/${map}_lower_radar_psd.png`,
    path.join(OUT_IMG, `${map}_lower.png`),
  );
  await download(`${BASE}/images/radars/${map}_radar_psd.png`, path.join(OUT_IMG, `${map}.png`));
  meta[map] = {
    posX: num(info, "pos_x"),
    posY: num(info, "pos_y"),
    scale: num(info, "scale"),
    lowerBelowZ: hasLower ? lowerSplit(info) : null,
    bombA: point(info, "bombA"),
    bombB: point(info, "bombB"),
  };
  console.log(map, meta[map]);
}

await fs.writeFile(
  OUT_META,
  `// Generated by scripts/fetch-radars.mjs — do not edit by hand.\n` +
    `export type RadarInfo = {\n  posX: number;\n  posY: number;\n  scale: number;\n  lowerBelowZ: number | null;\n  bombA: [number, number] | null;\n  bombB: [number, number] | null;\n};\n\n` +
    `export const RADARS: Record<string, RadarInfo> = ${JSON.stringify(meta, null, 2)};\n`,
);
console.log("wrote", OUT_META);
